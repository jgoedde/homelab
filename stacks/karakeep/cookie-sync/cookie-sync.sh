#!/bin/sh
# cookie-sync: merges all Netscape cookie files in $SRC_DIR (e.g. one export
# per domain: youtube_cookies.txt, reddit_cookies.txt, ...) into:
#   $OUT_DIR/cookies.txt   -> merged file for yt-dlp (writable, yt-dlp writes it back)
#   $OUT_DIR/cookies.json  -> derived from the merged file, for BROWSER_COOKIE_PATH
# Whenever any source file is added, changed or removed, the target compose
# service is restarted.
#
# Env:
#   SRC_DIR         source directory (default /src), all *.txt files are merged
#   OUT_DIR         output directory (default /out)
#   TARGET_SERVICE  compose service to restart (default web)
#   POLL_INTERVAL   seconds between checks (default 10)

set -eu

SRC_DIR="${SRC_DIR:-/src}"
OUT_DIR="${OUT_DIR:-/out}"
TARGET_SERVICE="${TARGET_SERVICE:-web}"
POLL_INTERVAL="${POLL_INTERVAL:-10}"

log() { echo "[cookie-sync] $(date '+%F %T') $*"; }

# Prints the source files in sorted order (glob expansion is sorted).
# Returns non-zero if there are none.
list_sources() {
  found=1
  for f in "$SRC_DIR"/*.txt; do
    [ -f "$f" ] || continue
    printf '%s\n' "$f"
    found=0
  done
  return "$found"
}

# Merges Netscape cookie files into one. Duplicates (same domain + path + name)
# are resolved by "last one wins", i.e. the alphabetically later file wins.
merge() {
  list_sources | while IFS= read -r f; do cat "$f"; echo; done | awk -F'\t' '
    { sub(/\r$/, "") }
    /^[[:space:]]*$/ { next }
    /^#/ && !/^#HttpOnly_/ { next }   # skip comments, keep HttpOnly entries
    NF < 7 { next }
    {
      domain = $1
      sub(/^#HttpOnly_/, "", domain)
      key = domain SUBSEP $3 SUBSEP $6
      if (!(key in line)) order[++n] = key
      line[key] = $0
    }
    END {
      print "# Netscape HTTP Cookie File"
      print "# Generated by cookie-sync. Do not edit, changes will be overwritten."
      for (i = 1; i <= n; i++) print line[order[i]]
    }
  '
}

# Converts a Netscape cookie file into the JSON format of Karakeep's cookiesSchema.
convert() {
  jq -R -s '
    split("\n")
    | map(
        sub("\r$"; "")
        | . as $line
        | ($line | startswith("#HttpOnly_")) as $httpOnly
        | (if $httpOnly then $line[10:] else $line end)
        | select(length > 0 and (startswith("#") | not))
        | split("\t")
        | select(length >= 7)
        | {
            name:     .[5],
            value:    (.[6:] | join("\t")),
            domain:   .[0],
            path:     .[2],
            secure:   (.[3] | ascii_upcase == "TRUE"),
            httpOnly: $httpOnly
          }
          + (
              # expires 0 or empty means session cookie -> omit the field
              (.[4] // "0") as $exp
              | if ($exp | test("^[0-9]+(\\.[0-9]+)?$")) and ($exp | tonumber) > 0
                then { expires: ($exp | tonumber) }
                else {}
                end
            )
      )
  ' "$1"
}

sync_files() {
  # Write to temp files first, then rename atomically so Karakeep and
  # yt-dlp never see a half-written file.
  merge > "$OUT_DIR/.cookies.txt.tmp"
  convert "$OUT_DIR/.cookies.txt.tmp" > "$OUT_DIR/.cookies.json.tmp"
  mv "$OUT_DIR/.cookies.txt.tmp"  "$OUT_DIR/cookies.txt"
  mv "$OUT_DIR/.cookies.json.tmp" "$OUT_DIR/cookies.json"
  log "synced $(jq length "$OUT_DIR/cookies.json") cookies from: $(list_sources | xargs -n1 basename | tr '\n' ' ')"
}

restart_target() {
  # Determine the compose project from this container's own labels.
  project="$(docker inspect -f '{{ index .Config.Labels "com.docker.compose.project" }}' "$(hostname)")"
  ids="$(docker ps -q \
          --filter "label=com.docker.compose.project=$project" \
          --filter "label=com.docker.compose.service=$TARGET_SERVICE")"
  if [ -n "$ids" ]; then
    log "restarting '$TARGET_SERVICE' (project: $project)"
    # shellcheck disable=SC2086
    docker restart $ids >/dev/null
  else
    log "no running container found for '$TARGET_SERVICE'"
  fi
}

# Hash over file names and contents, so adding, removing and editing
# files are all detected.
hash_sources() {
  list_sources | while IFS= read -r f; do
    printf '%s ' "$(basename "$f")"
    sha256sum "$f" | cut -d' ' -f1
  done | sha256sum | cut -d' ' -f1
}

# --- Initial run (before Karakeep starts) ---
until list_sources >/dev/null; do
  log "waiting for *.txt files in $SRC_DIR ..."
  sleep "$POLL_INTERVAL"
done
mkdir -p "$OUT_DIR"
sync_files
last="$(hash_sources)"
touch /tmp/ready # used by the healthcheck

# --- Watch loop (polling is robust against editors/exporters replacing files) ---
while sleep "$POLL_INTERVAL"; do
  cur="$(hash_sources)"
  if [ "$cur" != "$last" ]; then
    log "change detected in $SRC_DIR"
    if ! list_sources >/dev/null; then
      log "no source files left, keeping the previous cookies"
    elif sync_files; then
      restart_target
    else
      log "sync failed, keeping the previous cookies"
      continue
    fi
    last="$cur"
  fi
done
